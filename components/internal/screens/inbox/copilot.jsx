"use client";

// Inbox copilot pieces: summary panel, composer AI menu + "AI-generated" strip, inline translation; nothing here sends anything.

import {
  Badge,
  Button,
  DropdownMenu,
  DropdownMenuContent,
  DropdownMenuItem,
  DropdownMenuLabel,
  DropdownMenuSeparator,
  DropdownMenuTrigger,
  LogoLoading,
} from "@geiger/ui";
import { AlertCircle, Languages, Loader2, RotateCw, ShieldAlert, Sparkles, StickyNote, Undo2, X } from "lucide-react";
import { cn } from "@/lib/utils";
import { Notice } from "@/components/internal/shared/notice";
import { AiUnavailableNotice } from "@/components/internal/shared/ai_unavailable";
import { featureAvailability } from "@/lib/ai/features";
import { languageName } from "@/lib/kb/prompts";
import { MAX_DRAFT_CHARS } from "@/lib/inbox/copilot_prompts";

const COMPOSE_ITEMS = [
  ["rephrase", "Rephrase", "Rephrased"],
  ["friendlier", "Make friendlier", "Made friendlier"],
  ["formal", "Make more formal", "Made more formal"],
  ["shorten", "Shorten", "Shortened"],
  ["expand", "Expand", "Expanded"],
  ["fix", "Fix spelling & grammar", "Spelling and grammar fixed"],
];
export const COMPOSE_DONE = Object.fromEntries(COMPOSE_ITEMS.map(([action, , done]) => [action, done]));

const ERROR_COPY = {
  input_too_long: `AI works on drafts up to ${MAX_DRAFT_CHARS.toLocaleString("en-US")} characters.`,
  language_unknown: "Couldn't tell the customer's language. Set Language on their profile, then try again.",
  nothing_to_summarize: "There's nothing to summarize in this conversation yet.",
  not_found: "This conversation isn't available anymore.",
};

// The toast / inline text for a failed copilot call: our own copy for request problems, the server's mapped text for AI ones.
export function copilotError(res) {
  if (res.code === "same_language") return `It's already in ${languageName(res.language)}.`;
  return ERROR_COPY[res.code] ?? res.message;
}

// A refusal that means the cached AI status is stale (switched off, consent withdrawn, cap used up, key rejected).
export const isAiRefusal = (code) => Boolean(code?.startsWith("ai_")) || code === "provider_auth";

const pluralLinks = (n) => `${n} ${n === 1 ? "link" : "links"}`;

export function AiBadge({ children = "AI-generated" }) {
  return (
    <Badge variant="purple" className="shrink-0">
      <Sparkles /> {children}
    </Badge>
  );
}

// summary: { state: loading | ready | error | unavailable, text, provider, model, removed, message }
export function SummaryPanel({ summary, status, canInsert, onInsert, onRetry, onDismiss }) {
  const reason = featureAvailability(status, "inboxAssist").reason;
  let body;
  if (summary.state === "loading") {
    body = (
      <div className="flex justify-center py-3">
        <LogoLoading size={32} aria-label="Summarizing the conversation" />
      </div>
    );
  } else if (summary.state === "unavailable") {
    body = reason ? (
      <AiUnavailableNotice status={status} feature="inboxAssist" />
    ) : (
      <Button variant="outline" size="xs" className="border-border bg-transparent" onClick={onRetry}>
        <Sparkles /> Summarize
      </Button>
    );
  } else if (summary.state === "error") {
    body = (
      <Notice
        icon={AlertCircle}
        action={
          <Button variant="outline" size="xs" className="border-border bg-transparent" onClick={onRetry}>
            <RotateCw /> Retry
          </Button>
        }
      >
        {summary.message}
      </Notice>
    );
  } else {
    body = (
      <>
        <p className="max-h-56 overflow-y-auto whitespace-pre-wrap text-sm leading-[1.55] text-foreground">{summary.text}</p>
        {summary.removed ? (
          <p className="mt-2 inline-flex items-center gap-1 text-xs text-amber-300">
            <ShieldAlert className="h-3 w-3 shrink-0" /> Removed {pluralLinks(summary.removed)} the model added.
          </p>
        ) : null}
        <div className="mt-2.5 flex flex-wrap items-center gap-2">
          <p className="mr-auto text-xs text-text-tertiary">
            Generated by {summary.provider} · {summary.model}. Uses internal notes, so keep it within the team.
          </p>
          <Button variant="ghost" size="xs" className="text-muted-foreground" onClick={onRetry}>
            <RotateCw /> Regenerate
          </Button>
          <Button variant="outline" size="xs" className="border-border bg-transparent" disabled={!canInsert} onClick={onInsert}>
            <StickyNote /> Insert as note
          </Button>
        </div>
      </>
    );
  }

  return (
    <section aria-label="Conversation summary" className="shrink-0 border-b border-border bg-surface-subtle px-4 py-3 sm:px-5">
      <div className="mx-auto max-w-[760px]">
        <div className="mb-2 flex items-center gap-2">
          <Sparkles className="h-3.5 w-3.5 shrink-0 text-violet-300" aria-hidden="true" />
          <h3 className="text-[13px] font-semibold text-foreground">Conversation summary</h3>
          {summary.state === "ready" ? <AiBadge /> : null}
          <Button variant="ghost" size="icon-xs" className="ml-auto text-muted-foreground" aria-label="Dismiss summary" onClick={onDismiss}>
            <X />
          </Button>
        </div>
        {body}
      </div>
    </section>
  );
}

// The composer's AI menu (reply mode only): six rewrites of the draft, then a translation into the customer's language.
export function ComposerAiMenu({ status, loading, busy, draft, className, onRun }) {
  const assist = featureAvailability(status, "inboxAssist");
  const translation = featureAvailability(status, "inboxTranslation");
  const text = draft.trim();
  const hint = !text ? "Write a reply first — AI works on your draft." : text.length > MAX_DRAFT_CHARS ? ERROR_COPY.input_too_long : null;
  const off = loading || busy || Boolean(hint);
  // One notice when both features are off for the same reason.
  const translationNotice = !loading && !translation.available && (assist.available || translation.reason !== assist.reason);

  return (
    <DropdownMenu>
      <DropdownMenuTrigger asChild>
        <Button type="button" variant="ghost" size="sm" className={cn("h-7 gap-1 px-2 text-xs", className)} disabled={busy}>
          {busy ? <Loader2 className="h-3.5 w-3.5 animate-spin" /> : <Sparkles className="h-3.5 w-3.5" />} AI
        </Button>
      </DropdownMenuTrigger>
      <DropdownMenuContent align="start" side="top" className="w-64 border-border bg-surface-subtle">
        {!loading && !assist.available ? (
          <>
            <div className="px-2 py-1.5">
              <AiUnavailableNotice status={status} feature="inboxAssist" compact />
            </div>
            <DropdownMenuSeparator />
          </>
        ) : hint ? (
          <DropdownMenuLabel className="text-xs font-normal text-muted-foreground">{hint}</DropdownMenuLabel>
        ) : null}
        {COMPOSE_ITEMS.map(([action, label]) => (
          <DropdownMenuItem key={action} className="text-xs" disabled={off || !assist.available} onSelect={() => onRun(action)}>
            {label}
          </DropdownMenuItem>
        ))}
        <DropdownMenuSeparator />
        {translationNotice ? (
          <div className="px-2 py-1.5">
            <AiUnavailableNotice status={status} feature="inboxTranslation" compact />
          </div>
        ) : null}
        <DropdownMenuItem className="text-xs" disabled={off || !translation.available} onSelect={() => onRun("translate")}>
          <Languages /> Translate to the customer&apos;s language
        </DropdownMenuItem>
      </DropdownMenuContent>
    </DropdownMenu>
  );
}

// Shown while the draft is unedited AI text: what produced it, and the one-step undo.
export function AiDraftStrip({ ai, inReply, mod, onUndo }) {
  return (
    <div className="px-3 pb-2">
      <div className="flex flex-wrap items-center gap-x-2 gap-y-1 text-xs">
        <AiBadge />
        <span className="min-w-0 truncate text-muted-foreground">
          {ai.label}
          {ai.model ? ` · ${ai.model}` : ""}
        </span>
        {ai.removed ? <span className="text-amber-300">Removed {pluralLinks(ai.removed)} the model added</span> : null}
        <Button type="button" variant="ghost" size="xs" className="ml-auto text-muted-foreground" title={`Undo (${mod}+Z)`} onClick={onUndo}>
          <Undo2 /> Undo
        </Button>
      </div>
      {ai.kind === "summary" && inReply ? (
        <p className="mt-1 text-xs text-amber-300">This summary uses internal notes. Add it as a note, or edit it before replying.</p>
      ) : null}
    </div>
  );
}

// Under a customer message: the on-demand Translate action, then its progress, result toggle or failure.
// translation: { state: loading | ready | error | unavailable, sourceLanguage, truncated, original, message }
export function MessageTranslation({ message, translation, status, onTranslate, onToggleOriginal, onDismiss }) {
  const link = "underline-offset-2 transition-colors hover:text-foreground hover:underline";
  if (!translation) {
    return (
      <button
        type="button"
        onClick={() => onTranslate(message)}
        className="inline-flex items-center gap-1 text-xs text-muted-foreground opacity-0 transition-opacity hover:text-foreground focus-visible:opacity-100 group-hover:opacity-100 pointer-coarse:opacity-100"
      >
        <Languages className="h-3 w-3" /> Translate
      </button>
    );
  }
  if (translation.state === "loading") {
    return (
      <span role="status" className="inline-flex items-center gap-1 text-xs text-muted-foreground">
        <Loader2 className="h-3 w-3 animate-spin" /> Translating…
      </span>
    );
  }
  if (translation.state === "unavailable") {
    return (
      <div className="flex max-w-sm items-start gap-2">
        <AiUnavailableNotice status={status} feature="inboxTranslation" compact />
        <Button variant="ghost" size="icon-xs" className="shrink-0 text-muted-foreground" aria-label="Dismiss" onClick={() => onDismiss(message.id)}>
          <X />
        </Button>
      </div>
    );
  }
  if (translation.state === "error") {
    return (
      <span role="alert" className="inline-flex flex-wrap items-center gap-x-2 gap-y-1 text-xs text-red-400">
        <AlertCircle className="h-3 w-3 shrink-0" />
        {translation.message}
        <button type="button" className={cn("text-muted-foreground", link)} onClick={() => onTranslate(message)}>
          Retry
        </button>
        <button type="button" className={cn("text-muted-foreground", link)} onClick={() => onDismiss(message.id)}>
          Dismiss
        </button>
      </span>
    );
  }
  const from = translation.sourceLanguage ? `from ${languageName(translation.sourceLanguage)}` : null;
  return (
    <span className="inline-flex flex-wrap items-center gap-x-2 gap-y-1 text-xs text-muted-foreground">
      {translation.original ? <span>Original</span> : <AiBadge>AI translation</AiBadge>}
      {!translation.original && from ? <span>{from}</span> : null}
      {!translation.original && translation.truncated ? <span>· first part only</span> : null}
      <button type="button" className={link} onClick={() => onToggleOriginal(message.id)}>
        {translation.original ? "Show translation" : "Show original"}
      </button>
    </span>
  );
}
